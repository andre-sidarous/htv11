export const loadTransitStops = once((): TransitStop[] =>
  (ttcStopsRaw as unknown as CompactStop[]).map(([id, name, lat, lng, station]) => ({
    id,
    name,
    category: "transit",
    latitude: lat / 1e5,
    longitude: lng / 1e5,
    source: "TTC GTFS",
    kind: station ? "subway_station" : "surface_stop",
  })),
);
export const loadSubwayStations = (): TransitStop[] => loadTransitStops().filter((s) => s.kind === "subway_station");
export const loadTransitLines = (): TransitLine[] => ttcRoutesRaw as TransitLine[];
/** Walkable segments (sidewalk on at least one side, or a city walkway) across Toronto. */
export const loadPedestrianNetwork = once((): LatLng[][] => (pedestrianRaw as number[][]).map(decodeLine));
/** Named streets across Toronto. */
export const loadCentreline = once((): Street[] =>
  (centrelineRaw as CompactStreet[]).map((s) => ({ name: s.n, type: s.t, segments: s.s.map(decodeLine) })),
);

/**
 * Current transit disruption. The POC uses the local mock feed (campus-walk.json); the real
 * source would be TTC GTFS-Realtime service alerts, which we don't fetch at runtime.
 */
export function loadTransitDisruption(): TransitDisruption {
  const d = campusWalk.mockDisruption;
  const target = d.station.replace(/^St /, "St. ").toLowerCase();
  const station = loadSubwayStations().find((s) => s.name.toLowerCase() === target);
  return { ...d, location: station ? { latitude: station.latitude, longitude: station.longitude } : null };
}

/**
 * Points that are < `withinM` apart with the same category are treated as the same place.
 * Grid-bucketed (cells ≥ withinM) so citywide lists stay fast: only neighbouring cells are compared.
 */
export function dedupe(list: SupportPoint[], withinM = 40): SupportPoint[] {
  const cell = (withinM / 111_320) * 1.5;
  const key = (i: number, j: number) => `${i}:${j}`;
  const grid = new Map<string, SupportPoint[]>();
  const ids = new Set<string>();
  const out: SupportPoint[] = [];
  for (const point of list) {
    if (ids.has(point.id)) continue;
    const i = Math.floor(point.latitude / cell);
    const j = Math.floor(point.longitude / cell);
    let duplicate = false;
    for (let di = -1; di <= 1 && !duplicate; di++)
      for (let dj = -1; dj <= 1 && !duplicate; dj++)
        duplicate = (grid.get(key(i + di, j + dj)) ?? []).some((p) => p.category === point.category && haversineM(p, point) < withinM);
    if (duplicate) continue;
    ids.add(point.id);
    out.push(point);
    const bucket = grid.get(key(i, j));
    if (bucket) bucket.push(point);
    else grid.set(key(i, j), [point]);
  }
  return out;
}

let cached: SupportPoint[] | null = null;

/**
 * Every support point for the map and the route recommendation: the Campus Walk demo points
 * first (they carry the demo ids), then Toronto Open Data / OSM. Subway stations stand in for
 * transit; surface stops are only used for proximity.
 */
export function loadAllSupportPoints(): SupportPoint[] {
  cached ??= dedupe([
    ...campusWalk.supportPoints,
    ...loadLibraries(),
    ...loadCommunityCentres(),
    ...loadHospitals(),
    ...loadPolice(),
    ...loadWashrooms(),
    ...loadSchools(),
    ...loadParks(),
    ...loadSubwayStations(),
  ]);
  return cached;
}
