/**
 * Civic data for the whole City of Toronto: preprocessed JSON from the City of Toronto Open
 * Data Portal (+ OpenStreetMap hospitals), generated by data/extract/extract-toronto.mjs.
 * Imported statically; nothing is fetched at runtime, so this works with no network.
 *
 * The big line files (pedestrian network, centreline) and TTC stops are stored compactly and
 * decoded once on first use. Citywide lists are large (≈4.5k support points, 7k stops, 60k
 * sidewalk segments), so per-call code should use the *InBox / boxAround helpers below.
 */

export type TransitStop = SupportPoint & { category: "transit"; kind: "subway_station" | "surface_stop" };

export type TransitLine = {
  id: string;
  shortName: string;
  name: string;
  mode: "subway" | "streetcar";
  color: string;
  segments: LatLng[][];
};

export type Street = { name: string; type: string; segments: LatLng[][] };

export type TransitDisruption = {
  id: string;
  line: string;
  station: string;
  message: string;
  source: string;
  location: LatLng | null;
};

const points = (raw: unknown) => raw as SupportPoint[];

// ---------- compact decoding (see encodeLine in the extract script) ----------

/** [lat0, lng0, dLat, dLng, ...] in 1e-5 degrees → LatLng[]. */
export function decodeLine(encoded: readonly number[]): LatLng[] {
  const out: LatLng[] = [];
  let lat = 0;
  let lng = 0;
  for (let i = 0; i + 1 < encoded.length; i += 2) {
    lat += encoded[i]!;
    lng += encoded[i + 1]!;
    out.push({ latitude: lat / 1e5, longitude: lng / 1e5 });
  }
  return out;
}

type CompactStreet = { n: string; t: string; s: number[][] };
type CompactStop = [id: string, name: string, latE5: number, lngE5: number, station: 0 | 1];

const once = <T,>(load: () => T) => {
  let value: T | undefined;
  return () => (value ??= load());
};

// ---------- boxes ----------

export type Box = { south: number; north: number; west: number; east: number };

/** Bounding box of `points`, grown by `marginM` metres on every side. */
export function boxAround(points: readonly LatLng[], marginM = 0): Box {
  let south = Infinity, north = -Infinity, west = Infinity, east = -Infinity;
  for (const p of points) {
    south = Math.min(south, p.latitude);
    north = Math.max(north, p.latitude);
    west = Math.min(west, p.longitude);
    east = Math.max(east, p.longitude);
  }
  const dLat = marginM / 111_320;
  const dLng = marginM / (111_320 * Math.cos((((south + north) / 2) * Math.PI) / 180) || 1);
  return { south: south - dLat, north: north + dLat, west: west - dLng, east: east + dLng };
}

export const inBox = (box: Box, p: LatLng) =>
  p.latitude >= box.south && p.latitude <= box.north && p.longitude >= box.west && p.longitude <= box.east;

const lineInBox = (box: Box, line: readonly LatLng[]) => line.some((p) => inBox(box, p));

export const pointsInBox = <T extends LatLng>(list: readonly T[], box: Box): T[] => list.filter((p) => inBox(box, p));

/** Lines with at least one vertex inside the box (segments are short, so that's enough). */
export const linesInBox = (lines: readonly LatLng[][], box: Box): LatLng[][] => lines.filter((line) => lineInBox(box, line));

/** Streets with their segments trimmed to the ones touching the box. */
export function streetsInBox(box: Box, streets: readonly Street[] = loadCentreline()): Street[] {
  const out: Street[] = [];
  for (const street of streets) {
    const segments = street.segments.filter((segment) => lineInBox(box, segment));
    if (segments.length) out.push({ ...street, segments });
  }
  return out;
}

