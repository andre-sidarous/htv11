import { campusWalk } from "@/lib/demo/campusWalk";
import { haversineM } from "@/lib/geo";
import type { LatLng, SupportPoint } from "@/lib/types";
import centrelineRaw from "./data/centreline.json";
import communityCentresRaw from "./data/community-centres.json";
import hospitalsRaw from "./data/hospitals.json";
import librariesRaw from "./data/libraries.json";
import parksRaw from "./data/parks.json";
import pedestrianRaw from "./data/pedestrian-network.json";
import policeRaw from "./data/police.json";
import schoolsRaw from "./data/schools.json";
import ttcRoutesRaw from "./data/ttc-routes.json";
import ttcStopsRaw from "./data/ttc-stops.json";
import washroomsRaw from "./data/washrooms.json";

/**
 * Civic data for the Campus Walk area: small, preprocessed JSON from the City of Toronto
 * Open Data Portal (+ OpenStreetMap hospitals), generated by data/extract/extract-toronto.mjs.
 * Imported statically; nothing is fetched at runtime, so this works with no network.
 */

export type TransitStop = SupportPoint & { category: "transit"; kind: "subway_station" | "surface_stop" };

export type TransitLine = {
  id: string;
  shortName: string;
  name: string;
  mode: "subway" | "streetcar";
  color: string;
  segments: LatLng[][];
};

export type Street = { name: string; type: string; segments: LatLng[][] };

export type TransitDisruption = {
  id: string;
  line: string;
  station: string;
  message: string;
  source: string;
  location: LatLng | null;
};

const points = (raw: unknown) => raw as SupportPoint[];

export const loadLibraries = (): SupportPoint[] => points(librariesRaw);
export const loadSchools = (): SupportPoint[] => points(schoolsRaw);
export const loadCommunityCentres = (): SupportPoint[] => points(communityCentresRaw);
export const loadParks = (): SupportPoint[] => points(parksRaw);
export const loadWashrooms = (): SupportPoint[] => points(washroomsRaw);
export const loadPolice = (): SupportPoint[] => points(policeRaw);
export const loadHospitals = (): SupportPoint[] => points(hospitalsRaw);
export const loadTransitStops = (): TransitStop[] => ttcStopsRaw as TransitStop[];
export const loadSubwayStations = (): TransitStop[] => loadTransitStops().filter((s) => s.kind === "subway_station");
export const loadTransitLines = (): TransitLine[] => ttcRoutesRaw as TransitLine[];
/** Walkable segments (sidewalk on at least one side, or a city walkway) along the Campus Walk corridor. */
export const loadPedestrianNetwork = (): LatLng[][] => pedestrianRaw as LatLng[][];
export const loadCentreline = (): Street[] => centrelineRaw as Street[];

/**
 * Current transit disruption. The POC uses the local mock feed (campus-walk.json); the real
 * source would be TTC GTFS-Realtime service alerts, which we don't fetch at runtime.
 */
export function loadTransitDisruption(): TransitDisruption {
  const d = campusWalk.mockDisruption;
  const target = d.station.replace(/^St /, "St. ").toLowerCase();
  const station = loadSubwayStations().find((s) => s.name.toLowerCase() === target);
  return { ...d, location: station ? { latitude: station.latitude, longitude: station.longitude } : null };
}

/** Points that are < `withinM` apart with the same category are treated as the same place. */
function dedupe(list: SupportPoint[], withinM = 40): SupportPoint[] {
  const out: SupportPoint[] = [];
  for (const point of list) {
    const duplicate = out.some(
      (p) => p.category === point.category && (p.id === point.id || haversineM(p, point) < withinM),
    );
    if (!duplicate) out.push(point);
  }
  return out;
}

let cached: SupportPoint[] | null = null;

/**
 * Every support point for the map and the route recommendation: the Campus Walk demo points
 * first (they carry the demo ids), then Toronto Open Data / OSM. Subway stations stand in for
 * transit; surface stops are only used for proximity.
 */
export function loadAllSupportPoints(): SupportPoint[] {
  cached ??= dedupe([
    ...campusWalk.supportPoints,
    ...loadLibraries(),
    ...loadCommunityCentres(),
    ...loadHospitals(),
    ...loadPolice(),
    ...loadWashrooms(),
    ...loadSchools(),
    ...loadParks(),
    ...loadSubwayStations(),
  ]);
  return cached;
}
